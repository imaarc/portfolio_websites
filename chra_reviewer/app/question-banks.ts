export type Question = {
  topic: string;
  prompt: string;
  choices: string[];
  answer: number;
  explanation: string;
};

export type ReviewerBank = {
  id: string;
  label: string;
  shortLabel: string;
  title: string;
  searchPlaceholder: string;
  questions: Question[];
  quickRules: string[];
};

type Fact = {
  topic: string;
  term: string;
  correct: string;
  distractors: string[];
  explanation: string;
};

const choiceOrders = [
  [0, 1, 2, 3],
  [1, 2, 3, 0],
  [2, 3, 0, 1],
  [3, 0, 1, 2],
];

function buildChoices(correct: string, distractors: string[], offset: number) {
  const source = [correct, ...distractors.slice(0, 3)];
  const order = choiceOrders[offset % choiceOrders.length];
  const choices = order.map((index) => source[index]);
  return {
    choices,
    answer: choices.indexOf(correct),
  };
}

function makeQuestion(fact: Fact, index: number, variant: number): Question {
  const { choices, answer } = buildChoices(fact.correct, fact.distractors, index);
  const promptTemplates = [
    `For ${fact.term}, which answer is correct?`,
    `Which statement best describes ${fact.term}?`,
    `In the reviewer, ${fact.term} is most closely associated with:`,
    `A board-exam item asks about ${fact.term}. What should you remember?`,
    `Which option correctly completes this review note: ${fact.term} - ____?`,
  ];

  return {
    topic: fact.topic,
    prompt: promptTemplates[variant % promptTemplates.length],
    choices,
    answer,
    explanation: fact.explanation,
  };
}

function expandFacts(facts: Fact[], target: number) {
  const questions: Question[] = [];
  let variant = 0;

  while (questions.length < target) {
    for (let index = 0; index < facts.length && questions.length < target; index += 1) {
      questions.push(makeQuestion(facts[index], questions.length, variant));
    }
    variant += 1;
  }

  return questions;
}

